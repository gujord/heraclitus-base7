"""Export one committed marker record as untrusted Lean data, or check its binding.

This is a serializer, not a mathematical validator. It does not import src/
or a checker. Lean independently proves the data's greedy choices and states.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
KEY = "[[5,-6,[1,2,3]],74,1]"
NAME = "ladder-machine.json"


def lean_list(values):
    return "[" + ", ".join(str(x) for x in values) + "]"


def physical_word(edges, front):
    word = []
    for _before, _after, shift, value in edges:
        word.append(front + value)
        front += shift
    return word, front


def render(certificate_dir):
    payload = (certificate_dir / NAME).read_bytes()
    doc = json.loads(payload)
    cert = doc["certificates"][KEY]
    if doc["base"] != 7 or cert["prefix"]:
        raise ValueError("This selected bridge requires base 7 and an empty transient")
    f, c, b = cert["initial"]
    word, _ = physical_word(cert["cycle"], f)
    phase = cert["phase"]
    target = word[phase]
    phase_front = f + sum(edge[2] for edge in cert["cycle"][:phase])
    phase_current, phase_points = cert["cycle"][phase][0]
    marked_points = set(phase_points) | {target - phase_front}
    normalization = 0
    while normalization in marked_points:
        normalization += 1
    repair_front = phase_front - target + normalization
    repair, _ = physical_word(cert["repair"], repair_front)
    out_f, out_c, out_b = cert["output"]
    record_hash = hashlib.sha256(json.dumps(cert, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return f'''-- Generated by scripts/export_lean_certificate.py. Do not edit by hand.
-- Untrusted data only: Certificate74.lean proves the mathematical claims.
import Heraclitus.FiniteCertificate

set_option autoImplicit false

namespace Heraclitus.Certificate74Data

def sourceFile : String := "certificates/{NAME}"
def sourceKey : String := {json.dumps(KEY)}
def sourceSha256 : String := "{hashlib.sha256(payload).hexdigest()}"
def recordSha256 : String := "{record_hash}"

def initialFront : Int := {f}
def initialCurrent : Int := {c}
def initialExtra : List Int := {lean_list(b)}
def initial : FiniteState :=
  ⟨initialFront + initialCurrent, initialFront,
    initialExtra.map (fun x => initialFront + x)⟩

def period : Nat := {cert['modulus']}
def residue : Int := {cert['residue']}
def phase : Nat := {phase}
def cycleWord : List Int := {lean_list(word)}
def beforeWord : List Int := {lean_list(word[:phase])}
def target : Int := {target}
def afterWord : List Int := {lean_list(word[phase+1:])}

-- The post-insertion physical state, in coordinates relative to the target.
def repairInitial : FiniteState :=
  ⟨{phase_front + phase_current - target}, {repair_front}, {lean_list(sorted(phase_front + x - target for x in marked_points if x >= normalization))}⟩
def repairWord : List Int := {lean_list(repair)}

def outputFront : Int := {out_f}
def outputCurrent : Int := {out_c}
def outputExtra : List Int := {lean_list(out_b)}
def output : FiniteState :=
  ⟨outputFront + outputCurrent, outputFront,
    outputExtra.map (fun x => outputFront + x)⟩

end Heraclitus.Certificate74Data
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--certificates", type=Path, default=REPO / "certificates")
    parser.add_argument("--output", type=Path, default=REPO / "formal/Heraclitus/Certificate74Data.lean")
    parser.add_argument("--check", action="store_true", help="Check exact data binding without writing")
    args = parser.parse_args()
    expected = render(args.certificates)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != expected:
            raise SystemExit("Lean data binding mismatch; regenerate and re-prove before accepting changes")
        print("Selected JSON-to-Lean data binding matches (identity check, not a proof).")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected)
        print(f"Wrote untrusted certificate data: {args.output}")


if __name__ == "__main__":
    main()
