"""Bind signed return rows to checked ladder bottoms; Lean checks the match.

This untrusted exporter imports neither producer nor mathematical checker.
Both source certificate identities are embedded in the generated Lean file.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SIGNED = REPO / "certificates/signed-machine.json"
LADDER = REPO / "certificates/ladder-machine.json"
TARGET = REPO / "formal/Heraclitus/SignedBottomData.lean"


def render(signed=SIGNED, ladder=LADDER):
    sr, lr = signed.read_bytes(), ladder.read_bytes()
    sd, ld = json.loads(sr), json.loads(lr)
    rows, cases = sd["transitions"], ld["cases"]
    if sd["base"] != 7 or ld["base"] != 7 or [r["k"] for r in rows] != list(range(40, 76)):
        raise ValueError("Expected base seven and all 36 signed rows")
    keys = [(c["case"]["offset"], c["case"]["core"]) for c in cases]
    if len(keys) != 18 or len({json.dumps(k) for k in keys}) != 18:
        raise ValueError("Expected 18 distinct ladder cases")
    lines = ["import Heraclitus.SignedBottom", "import Heraclitus.ReturnBridgeData",
             "import Heraclitus.LadderBottomData", "", "set_option autoImplicit false",
             "set_option maxRecDepth 100000", "", "/-! Generated by research/signed_bottom/export_data.py.",
             "Signed source SHA-256: " + hashlib.sha256(sr).hexdigest(),
             "Ladder source SHA-256: " + hashlib.sha256(lr).hexdigest(), "-/", "",
             "namespace Heraclitus.SignedBottomData", "open SignedBottom ReturnBridgeData LadderBottomData", ""]
    summary = []
    for r in rows:
        label = r["k"]
        if not r["anchor_used"]:
            if label != 43 or r["bottom"] != [1] or r["first_exit"]["entry"] != 2:
                raise ValueError("Unexpected unused-anchor branch")
            continue
        key = (r["core"]["offset"], r["core"]["core"])
        index = keys.index(key)
        lines += [f"theorem match{label} : Match entrance{label} checkedBottom{index:02d} := by decide",
                  f"def case{label} : CheckedCase := ⟨entrance{label}, checkedBottom{index:02d}, match{label}⟩", ""]
        summary.append({"label": label, "bottom": index})
    lines += ["theorem match43 : ShortMatch entrance43 := by decide", "",
              "def catalogue : List CheckedCase := [" + ", ".join(f"case{r['label']}" for r in summary) + "]", "",
              "theorem entrances_agree : catalogue.map (fun c => c.entrance) =",
              "    ReturnBridgeData.catalogue.filter (fun e => e.data.anchorUsed) := rfl", "",
              "theorem labels_complete : catalogue.map (fun c => c.entrance.outgoing.row.label) =",
              "    ((List.range 36).map (fun i => i+40)).filter (fun i => i != 43) := by decide", "",
              "def bottomIndices : List Nat := [" + ", ".join(str(r["bottom"]) for r in summary) + "]", "",
              "theorem all_bottom_indices : bottomIndices.eraseDups = List.range 18 := by decide", "",
              "/-- Specialization of the short branch; validity, exact endpoint and count",
              "are supplied by SignedBottom.short_all_exponents. -/",
              "theorem phase43_all_exponents (t : Nat) (C : Int)",
              "    (scale : 2*C+1=(7^(entrance43.outgoing.row.leastExponent+36*t) : Nat)) :",
              "    ∃ q : Nat, ∃ b : SignedBlock (entrance43.outgoing.inner.initial.toState C)",
              "      (OutgoingWord.liftRay (!entrance43.outgoing.row.positive) C",
              "        (ReturnBridge.farBoundary entrance43.outgoing q)",
              "        (shortEnd (7^(entrance43.outgoing.row.leastExponent+36*t) : Nat)).toState),",
              "      b.word.length=entrance43.outgoing.inner.moves.length+q*entrance43.outgoing.row.phases.size+",
              "        entrance43.outgoing.row.selected.val+5 ∧",
              "      3*(7^(entrance43.outgoing.row.leastExponent+36*t) : Nat)-200 ≤",
              "        (ReturnBridge.farBoundary entrance43.outgoing q).front :=",
              "  short_all_exponents entrance43 match43 t C scale", "",
              "end Heraclitus.SignedBottomData"]
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--signed", type=Path, default=SIGNED)
    parser.add_argument("--ladder", type=Path, default=LADDER)
    args = parser.parse_args()
    content, rows = render(args.signed, args.ladder)
    if args.write:
        if args.signed.resolve() != SIGNED.resolve() or args.ladder.resolve() != LADDER.resolve():
            raise SystemExit("Alternate sources cannot replace committed data")
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("Signed bottom source binding mismatch")
    print(json.dumps({"status": "binding matches", "used_rows": len(rows), "short_rows": [43],
                      "bottoms": len({r["bottom"] for r in rows})}, indent=2))


if __name__ == "__main__":
    main()
