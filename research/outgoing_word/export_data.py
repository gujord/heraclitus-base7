"""Bind the 36 outgoing half-line cycles to kernel-checkable Lean data.

Extraction is untrusted: finite edge/equality propositions are proved in
Lean, and the initial record is compared with the proved inner boundary.
No producer/checker mathematical code is imported.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "certificates/signed-machine.json"
TARGET = REPO / "formal/Heraclitus/OutgoingWordData.lean"


def integer(n):
    return f"({n})" if n < 0 else str(n)


def state(value):
    current, front, points = value
    return f"⟨{integer(current)}, {integer(front)}, [{', '.join(map(integer, points))}]⟩"


def render():
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    rows = data["transitions"]
    if data["base"] != 7 or [r["k"] for r in rows] != list(range(40, 76)):
        raise ValueError("Expected base seven and labels 40..75")
    lines = ["import Heraclitus.OutgoingWord", "import Heraclitus.OutgoingData",
             "import Heraclitus.SignedBoundaryData", "",
             "set_option autoImplicit false", "set_option maxRecDepth 100000",
             "set_option maxHeartbeats 40000000", "",
             "/-! Generated by research/outgoing_word/export_data.py.",
             "Source SHA-256: " + hashlib.sha256(raw).hexdigest(),
             "Each check is proved by kernel reduction. -/", "",
             "namespace Heraclitus.OutgoingWordData",
             "open OutgoingWord FirstCrossingData OutgoingData SignedBoundaryData", ""]
    summary = []
    for row in rows:
        k = row["k"]
        exit_data = row["first_exit"]
        if exit_data["prefix"]:
            raise ValueError("This binding requires an empty outgoing transient")
        front = exit_data["initial_front"]
        states, choices = [], []
        for before, after, advance, choice in exit_data["cycle"]:
            states.append((front + before[0], front, [front + x for x in before[1]]))
            choices.append(front + choice)
            front += advance
        states.append((front + after[0], front, [front + x for x in after[1]]))
        all_values = [x for current, f, points in states for x in [current, f, *points]] + choices
        lo, hi = min(all_values) - 1, max(all_values) + 1
        lines += [f"def cycle{k} : CycleData row{k} where", "  states := fun i => match i with"]
        for i, s in enumerate(states[:-1]):
            lines.append(f"    | {i} => {state(s)}")
        lines.append(f"    | _ => {state(states[-1])}")
        lines.append("  choices := fun i => match i with")
        for i, value in enumerate(choices):
            lines.append(f"    | {i} => {integer(value)}")
        lines += ["    | _ => 0", f"  lo := {integer(lo)}", f"  hi := {integer(hi)}", "",
                  f"theorem cycle{k}_checked : cycle{k}.Checked := by decide +kernel", "",
                  f"theorem entrance{k}_checked : row{k}_inner.final.equalityCheck",
                  f"    (record row{k}.positive geometry{k}.other (cycle{k}.states 0)) = true := by decide +kernel", ""]
        summary.append({"label": k, "phases": len(choices), "front_shift": front-exit_data["initial_front"],
                        "initial": states[0], "final": states[-1], "window": [lo, hi]})
    lines += ["def catalogue : List CertifiedRow := [",
              ",\n".join(f"  ⟨row{k}, geometry{k}, cycle{k}, row{k}_checked, geometry{k}_checked, "
                         f"cycle{k}_checked, row{k}_inner, entrance{k}_checked⟩" for k in range(40, 76)), "]", "",
              "theorem labels_complete : catalogue.map (fun c => c.row.label) =",
              "    (List.range 36).map (fun i => i+40) := by decide +kernel", "",
              "end Heraclitus.OutgoingWordData"]
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    content, rows = render()
    if args.write:
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("OutgoingWordData.lean does not match the source extraction")
    print(json.dumps({"status": "binding matches", "rows": len(rows),
                      "phases": sum(r["phases"] for r in rows)}, indent=2))


if __name__ == "__main__":
    main()
