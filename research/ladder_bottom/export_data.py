"""Export the 18 supplied finite bottom words as untrusted bitmap chunks.

This serializer only records choices and set updates. Lean independently
checks greedy legality, complete endpoints, source linkage and counts.
No imports from src/ or checker/. --check is the default.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = Path('formal/Heraclitus/LadderBottom')
MAIN = Path('formal/Heraclitus/LadderBottomData.lean')
CHUNK_SIZE = 64
SHARD_SIZE = 16


def ints(xs):
    return '[' + ', '.join(map(str, xs)) + ']'


def bitmap(cur, mask):
    return f'⟨{cur}, -200, {mask}⟩'


def preamble(imports):
    return ('-- Generated by research/ladder_bottom/export_data.py; kernel checking is required.\n' +
            ''.join('import ' + x + '\n' for x in imports) +
            '\nset_option autoImplicit false\nset_option maxRecDepth 100000\n' +
            'set_option maxHeartbeats 10000000\nset_option exponentiation.threshold 10000\n\n' +
            'namespace Heraclitus.LadderBottomData\nopen LadderBottom\n\n')


def render(certificate_dir):
    raw = (certificate_dir / 'ladder-machine.json').read_bytes()
    data = json.loads(raw)
    if data['base'] != 7:
        raise ValueError('Expected base seven')
    chunk_index = {}
    chunks = []
    cases = []
    keys = []
    for case in data['cases']:
        entry = case['case']
        a = entry['offset']
        keys.append(json.dumps(entry, sort_keys=True, separators=(',', ':')))
        used = set(range(-200, -100-a)) | {x-a for x in entry['core']} | {2401}
        if min(used) < -200:
            raise ValueError('Old-region point below bitmap lower bound')
        mask = sum(1 << (x+200) for x in used)
        cur = 2401
        word = [x-a for x in case['core']['word']]
        refs = []
        for start in range(0, len(word), CHUNK_SIZE):
            w = tuple(word[start:start+CHUNK_SIZE])
            key = (cur, mask, w)
            old_cur, old_mask = cur, mask
            for v in w:
                if v < -200:
                    raise ValueError('Choice below bitmap lower bound')
                mask |= 1 << (v+200)
                cur = v
            if key not in chunk_index:
                chunk_index[key] = len(chunks)
                chunks.append((old_cur, old_mask, w, cur, mask))
            refs.append(chunk_index[key])
        cases.append((case, refs))
    files = {}
    ending = '\nend Heraclitus.LadderBottomData\n'
    modules = []
    for start in range(0, len(chunks), SHARD_SIZE):
        name = f'Chunks{start//SHARD_SIZE:02}'
        modules.append('Heraclitus.LadderBottom.' + name)
        out = preamble(['Heraclitus.LadderBottom'])
        for i, (cur, mask, word, end_cur, end_mask) in enumerate(chunks[start:start+SHARD_SIZE], start):
            out += f'def chunk{i:03} : Chunk := {{\n  initial := {bitmap(cur, mask)}\n'
            out += f'  output := {bitmap(end_cur, end_mask)}\n  word := {ints(word)} }}\n'
            out += f'theorem chunk{i:03}_checked : chunk{i:03}.Claim := by decide\n'
            out += f'def checkedChunk{i:03} : CheckedChunk := ⟨chunk{i:03}, chunk{i:03}_checked⟩\n\n'
        files[BASE / (name + '.lean')] = out + ending
    files[BASE / 'Chunks.lean'] = ''.join('import ' + m + '\n' for m in modules)
    case_modules = []
    for first in range(0, len(cases), 3):
        name = f'Cases{first//3:02}'
        case_modules.append('Heraclitus.LadderBottom.' + name)
        out = preamble(['Heraclitus.LadderBottom.Chunks', 'Heraclitus.LadderDescentData',
                        'Heraclitus.LadderLayersData'])
        for i, (case, refs) in enumerate(cases[first:first+3], first):
            out += f'def bottom{i:02} : Bottom := {{\n'
            out += f'  entrance := LadderDescentData.checked{i:02}\n  ladder := LadderLayersData.checked{i:02}\n'
            out += '  chunks := [' + ', '.join(f'checkedChunk{k:03}' for k in refs) + ']\n'
            out += f'  moves := {len(case["core"]["word"])}\n'
            out += f'  maxCoordinate := {case["core"]["max_coordinate"]-case["case"]["offset"]}\n'
            out += f'  level := {case["core"]["J"]}\n  endCoordinate := {case["core"]["end"]} }}\n'
            out += f'theorem bottom{i:02}_checked : bottom{i:02}.Claim := by decide\n'
            out += f'def checkedBottom{i:02} : CheckedBottom := ⟨bottom{i:02}, bottom{i:02}_checked⟩\n\n'
        files[BASE / (name + '.lean')] = out + ending
    out = preamble(case_modules)
    out += 'def catalogue : List CheckedBottom := [' + ', '.join(f'checkedBottom{i:02}' for i in range(len(cases))) + ']\n'
    out += 'def sourceKeys : List String := [' + ', '.join(json.dumps(k) for k in keys) + ']\n'
    out += f'def sourceSha256 : String := "{hashlib.sha256(raw).hexdigest()}"\n'
    out += '''
theorem source_agrees : sourceKeys = LadderDescentData.sourceKeys ∧
    sourceKeys = LadderLayersData.sourceKeys := ⟨rfl, rfl⟩

theorem entrances_agree : catalogue.map (fun c => c.bottom.entrance) =
    LadderDescentData.catalogue := rfl

theorem ladders_agree : catalogue.map (fun c => c.bottom.ladder) =
    LadderLayersData.catalogue := rfl

theorem catalogue_complete : catalogue.length = 18 ∧
    (catalogue.map (fun c => c.bottom.moves)).sum = 43154 := by decide

theorem keys_distinct : sourceKeys.Nodup := by
  rw [source_agrees.1]
  exact LadderDescentData.catalogue_complete.2.2.1

theorem all_bottoms : ∀ c ∈ catalogue,
    ValidWord (LadderDescent.start c.bottom.entrance.entrance.old 2401) c.bottom.word ∧
      execute (LadderDescent.start c.bottom.entrance.entrance.old 2401) c.bottom.word =
        translate 2401 c.bottom.ladder.ladder.initial.toState ∧
      c.bottom.word.length = c.bottom.moves ∧
      (∀ x ∈ c.bottom.word, -100 ≤ x+c.bottom.entrance.entrance.anchor ∧ x < 4401) := by
  intro c _hc
  exact c.bottom.sound c.checked

/-- Descent, concrete bottom and all higher layers; no bottom-word premise remains. -/
theorem all_heights : ∀ c ∈ catalogue, ∀ n,
    ∃ w : List Int,
      ValidWord (c.bottom.entrance.entrance.initial n) w ∧
      execute (c.bottom.entrance.entrance.initial n) w =
        translate (c.bottom.entrance.entrance.anchor+LadderLayers.scale n)
          (c.bottom.ladder.ladder.entry n).toState ∧
      (w.length : Int) = 6*(n : Int) + c.bottom.moves + LadderLayers.scale n - 2401 +
        c.bottom.ladder.ladder.cumulative 0 n := by
  intro c _hc n
  exact c.bottom.all_heights c.checked n

theorem all_bottoms_with_later : ∀ c ∈ catalogue, ∀ later : Int → Prop,
    (∀ x, later x → 4401 ≤ x) →
    ValidWord (mark (LadderDescent.start c.bottom.entrance.entrance.old 2401) later) c.bottom.word ∧
      execute (mark (LadderDescent.start c.bottom.entrance.entrance.old 2401) later) c.bottom.word =
        mark (translate 2401 c.bottom.ladder.ladder.initial.toState) later := by
  intro c _hc later far
  exact c.bottom.with_later c.checked later far
'''
    files[MAIN] = out + ending
    stats = {'case_count': len(cases), 'word_choices': sum(len(c['core']['word']) for c, _ in cases),
             'chunk_occurrences': sum(len(refs) for _, refs in cases), 'unique_chunks': len(chunks),
             'unique_chunk_choices': sum(len(c[2]) for c in chunks), 'chunk_size': CHUNK_SIZE,
             'generated_modules': len(files)}
    return files, stats


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--certificates', type=Path, default=ROOT / 'certificates')
    parser.add_argument('--root', type=Path, default=ROOT)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--write', action='store_true')
    action.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files, stats = render(args.certificates)
    for relative, expected in files.items():
        path = args.root / relative
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif not path.is_file() or path.read_text() != expected:
            raise SystemExit('Bottom source binding mismatch: ' + str(relative))
    print(json.dumps({'action': 'wrote' if args.write else 'matched', **stats,
                      'scope': 'Untrusted data identity, not a mathematical proof'}, sort_keys=True))


if __name__ == '__main__':
    main()
