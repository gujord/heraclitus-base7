"""Bind all approach rows to the exact already-checked transient/cycle data.

This serializer imports neither producer nor checker. It requires exact
route-array identity before reusing a transfer reference. Lean checks all
state matches, arithmetic, bounds, and the universal word theorem.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIGNED = ROOT / 'certificates/signed-machine.json'
LADDER = ROOT / 'certificates/ladder-machine.json'
TARGET = ROOT / 'formal/Heraclitus/ApproachWordData.lean'


def finite(front, state):
    current, points = state
    return f'⟨{front+current}, {front}, {json.dumps([front+x for x in points])}⟩'


def render(signed=SIGNED, ladder=LADDER):
    sr, lr = signed.read_bytes(), ladder.read_bytes()
    sd, ld = json.loads(sr), json.loads(lr)
    if sd['base'] != 7 or ld['base'] != 7 or [r['k'] for r in sd['transitions']] != list(range(40, 76)):
        raise ValueError('Expected all 36 base-seven phase labels')
    transfers = sorted(ld['certificates'].items())
    if len(transfers) != 119:
        raise ValueError('Expected 119 checked transfer records')
    out = '''-- Generated by research/approach_word/export_data.py; kernel checking is required.
import Heraclitus.ApproachWord
import Heraclitus.PostLadderData
import Heraclitus.ShortReturnData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.ApproachWordData
open ApproachWord TransferCertificate

'''
    summary = []
    for r in sd['transitions']:
        k, a = r['k'], r['approach']
        choices = [i for i, (key, c) in enumerate(transfers)
                   if json.loads(key)[0] == [a['initial_front'], *a['initial_state']]
                   and c['prefix'] == a['prefix'] and c['cycle'] == a['cycle']
                   and c['modulus'] == a['modulus']]
        if not choices:
            raise ValueError('No exact checked route match for phase ' + str(k))
        index = choices[0]
        exponent = 6+(k-6) % 36
        out += f'''def row{k} : Row := {{
  label := {k}
  leastExponent := {exponent}
  offset := {a['offset']}
  front := {a['front']}
  original := TransferCatalogue.row{index:03}
  initial := {finite(a['initial_front'], a['initial_state'])}
  output := {finite(a['front'], a['state'])} }}
theorem row{k}_checked : row{k}.Claim := by decide
def checked{k} : Checked := ⟨row{k}, row{k}_checked⟩

'''
        prior = ('PostLadderData.input' + str(k) + '.transfer' if k != 43
                 else 'ShortReturnData.second')
        out += f'''theorem input{k}_checked :
    sameState row{k}.initial {prior}.original.transfer.output = true := by decide

'''
        if k != 43:
            out += f'''theorem input{k}_all (t : Nat) :
    row{k}.start (row{k}.scale t) = PostLadderData.input{k}.endpoint t := by
  change mark (translate (2*row{k}.scale t+row{k}.offset) row{k}.initial.toState)
    (fun x => x=3*row{k}.scale t+row{k}.offset) =
      mark (translate (2*row{k}.scale t+row{k}.offset) {prior}.original.transfer.output.toState)
        (fun x => x=3*row{k}.scale t+row{k}.offset)
  rw [sameState_sound input{k}_checked]

'''
        else:
            out += '''theorem input43_all (t : Nat) :
    row43.start (row43.scale t) = (ShortReturn.finalState (row43.scale t)).toState := by
  unfold Row.start
  rw [sameState_sound input43_checked]
  exact ShortReturnData.chain.second_output (row43.scale t)

'''
        summary.append({'label': k, 'least_exponent': exponent, 'transfer': index,
                        'transient_edges': len(a['prefix']), 'period': a['modulus'],
                        'offset': a['offset'], 'front': a['front']})
    out += 'def catalogue : List Checked := [' + ', '.join(f'checked{r["label"]}' for r in summary) + ']\n'
    out += 'def signedSourceSha256 : String := "' + hashlib.sha256(sr).hexdigest() + '"\n'
    out += 'def ladderSourceSha256 : String := "' + hashlib.sha256(lr).hexdigest() + '"\n\n'
    out += '''theorem source_agrees : signedSourceSha256 = PostLadderData.signedSourceSha256 ∧
    ladderSourceSha256 = PostLadderData.ladderSourceSha256 := ⟨rfl, rfl⟩

theorem phases_agree : catalogue.map (fun c => (c.row.label, c.row.leastExponent)) =
    SignedLadderData.catalogue.map (fun c =>
      (c.entrance.outgoing.row.label, c.entrance.outgoing.row.leastExponent)) := rfl

theorem labels_complete : catalogue.map (fun c => c.row.label) =
    (List.range 36).map (fun i => i+40) := by decide

theorem all_exponents : ∀ c ∈ catalogue, ∀ t,
    ValidWord (c.row.start (c.row.scale t)) (c.row.word (c.row.scale t)) ∧
    execute (c.row.start (c.row.scale t)) (c.row.word (c.row.scale t)) =
      c.row.finish (c.row.scale t) ∧
    ((c.row.word (c.row.scale t)).length : Int) = c.row.moves (c.row.scale t) := by
  intro c _hc t
  exact c.all_exponents t

theorem all_bounds : ∀ c ∈ catalogue, ∀ t,
    (∀ x ∈ c.row.word (c.row.scale t),
      2*c.row.scale t-100 ≤ x ∧ x < 3*c.row.scale t-50) ∧
    2*c.row.scale t-100 ≤ (c.row.start (c.row.scale t)).current ∧
    (c.row.start (c.row.scale t)).current < 3*c.row.scale t-50 := by
  intro c _hc t
  exact c.bounds t

theorem all_floor_laws : ∀ c ∈ catalogue, ∀ t,
    (c.row.quotient (c.row.scale t) : Int) =
      (c.row.scale t-c.row.offset-256-c.row.original.transfer.entryFront) /
        c.row.original.transfer.modulus ∧
    c.row.original.transfer.entryFront+
      (c.row.quotient (c.row.scale t) : Int)*c.row.original.transfer.modulus =
        c.row.scale t-c.row.offset+c.row.front := by
  intro c _hc t
  exact c.floor_law t

end Heraclitus.ApproachWordData
'''
    return out, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--signed', type=Path, default=SIGNED)
    parser.add_argument('--ladder', type=Path, default=LADDER)
    args = parser.parse_args()
    text, rows = render(args.signed, args.ladder)
    if args.write:
        if args.signed.resolve() != SIGNED or args.ladder.resolve() != LADDER:
            raise SystemExit('Alternate sources cannot replace committed data')
        TARGET.write_text(text)
    elif TARGET.read_text() != text:
        raise SystemExit('Approach-word source binding mismatch')
    print(f'PASS: {len(rows)} approach rows bound to {len({r["transfer"] for r in rows})} checked transient/cycle pairs')


if __name__ == '__main__':
    main()
