"""Bind the exceptional phase and its ordered pair of concrete transfers.

This untrusted serializer imports neither producer nor mathematical checker.
Lean proves the state matches, shapes, residues and exact composition.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SIGNED = REPO / "certificates/signed-machine.json"
LADDER = REPO / "certificates/ladder-machine.json"
TARGET = REPO / "formal/Heraclitus/ShortReturnData.lean"


def render(signed=SIGNED, ladder=LADDER):
    sr, lr = signed.read_bytes(), ladder.read_bytes()
    sd, ld = json.loads(sr), json.loads(lr)
    if sd["base"] != 7 or ld["base"] != 7:
        raise ValueError("Expected base seven")
    if [r["k"] for r in sd["transitions"]] != list(range(40, 76)):
        raise ValueError("Expected complete signed phase catalogue")
    direct = [r for r in sd["transitions"] if not r["anchor_used"]]
    if len(direct) != 1 or direct[0]["k"] != 43:
        raise ValueError("Expected only phase 43 to have an unused anchor")
    row = direct[0]
    if row["bottom"] != [1] or row["first_exit"]["entry"] != 2 or len(row["transfer_keys"]) != 2:
        raise ValueError("Unexpected short branch data")
    keys = sorted(ld["certificates"])
    indices = [keys.index(key) for key in row["transfer_keys"]]
    lines = ["import Heraclitus.ShortReturn", "import Heraclitus.SignedLadderData",
             "import Heraclitus.SignedTransferData", "", "set_option autoImplicit false",
             "set_option maxRecDepth 100000", "", "/-! Generated by research/short_return/export_data.py.",
             "Signed source SHA-256: " + hashlib.sha256(sr).hexdigest(),
             "Ladder source SHA-256: " + hashlib.sha256(lr).hexdigest(), "-/", "",
             "namespace Heraclitus.ShortReturnData", "open ShortReturn OutgoingWord ReturnBridge", "",
             "def phase := SignedLadderData.phase43",
             f"def first := SignedTransferData.checked{indices[0]:03d}",
             f"def second := SignedTransferData.checked{indices[1]:03d}", "",
             "theorem first_shape : FirstShape first.original.transfer := by decide",
             "theorem second_shape : SecondShape second.original.transfer := by decide",
             "def chain : Chain := ⟨first, second, first_shape, second_shape⟩", "",
             "theorem phase_identity : phase.entrance.outgoing.row.label=43 ∧",
             "    phase.entrance.outgoing.row.leastExponent=7 ∧ phase.route.isLadder=false ∧",
             "    phase.entrance.outgoing.row.positive=false := by decide", "",
             "def sourceTransferKeys : List String := [" + ", ".join(json.dumps(k) for k in row["transfer_keys"]) + "]",
             "theorem transfer_keys_match : sourceTransferKeys =",
             f"    [TransferCatalogue.keys[{indices[0]}]!, TransferCatalogue.keys[{indices[1]}]!] := by decide", "",
             "theorem residue_all (t : Nat) : ((7^(phase.exponent t) : Nat) : Int)%8=7 := by",
             "  have periodic := FirstCrossing.exponent_residue 8 7 t (by decide)",
             "  have initial : (7^7 : Nat)%8=7 := by decide",
             "  rw [initial] at periodic",
             "  exact congrArg (fun n : Nat => (n : Int)) periodic", "",
             "theorem cycle_relation (t q : Nat) (index : phase.CycleIndex t q) :",
             "    8*(q : Int)=3*(7^(7+36*t) : Nat)-101 := by",
             "  change ∃ d : Int, 0 ≤ d ∧ (q : Int)=308816+3*d ∧",
             "    (7^(7+36*t) : Nat)=823543+8*d at index",
             "  obtain ⟨d, _nonnegative, count, scale⟩ := index", "  omega", "",
             "theorem exact_count (t q : Nat) (index : phase.CycleIndex t q) :",
             "    phase.moves t q+2*(7^(phase.exponent t) : Nat)-2 = 5*(7^(7+36*t) : Nat)+2 := by",
             "  have relation := cycle_relation t q index",
             "  change ((100+q*8+0+3 : Nat) : Int)+2+2*(7^(7+36*t) : Nat)-2 = _",
             "  simp only [Int.natCast_add, Int.natCast_mul]", "  omega", "",
             "/-- From the specified phase-43 inner state, through both concrete",
             "transfers. Reachability from zero and the later approach remain separate. -/",
             "theorem all_exponents (t : Nat) (C : Int)",
             "    (radius : 2*C+1=(7^(7+36*t) : Nat)) :",
             "    ∃ q : Nat, ∃ b : SignedBlock (phase.entrance.outgoing.inner.initial.toState C)",
             "      (liftRay true C (farBoundary phase.entrance.outgoing q)",
             "        (finalState (7^(7+36*t) : Nat)).toState),",
             "      (b.word.length : Int)=5*(7^(7+36*t) : Nat)+2 ∧",
             "      3*(7^(7+36*t) : Nat)-200 ≤ (farBoundary phase.entrance.outgoing q).front ∧",
             "      phase.CycleIndex t q := by",
             "  obtain ⟨q, b, count, filled, index⟩ := chain.all_exponents phase",
             "    phase_identity.2.2.1 t C radius (residue_all t)",
             "  exact ⟨q, b, count.trans (exact_count t q index), filled, index⟩", "",
             "end Heraclitus.ShortReturnData"]
    summary = {"phase": 43, "least_exponent": 7, "anchor": 2, "short_word": [2, 1],
               "transfer_indices": indices, "transfer_keys": row["transfer_keys"]}
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--signed", type=Path, default=SIGNED)
    parser.add_argument("--ladder", type=Path, default=LADDER)
    args = parser.parse_args()
    content, summary = render(args.signed, args.ladder)
    if args.write:
        if args.signed.resolve() != SIGNED.resolve() or args.ladder.resolve() != LADDER.resolve():
            raise SystemExit("Alternate sources cannot replace committed data")
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("Short return source binding mismatch")
    print(json.dumps({"status": "binding matches", **summary}, indent=2))


if __name__ == "__main__":
    main()
