"""Serialize the 18 ladder layer maps as untrusted Lean data.

The completed bottom states are inputs. This does not validate bottom
words, forced descent, or signed reachability. --check is the default.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'formal/Heraclitus/LadderLayersData.lean'


def finite(t):
    f, c, points = t
    return f'⟨{f + c}, {f}, [' + ', '.join(str(f + p) for p in points) + ']⟩'


def render(certificate_dir):
    raw = (certificate_dir / 'ladder-machine.json').read_bytes()
    data = json.loads(raw)
    if data['base'] != 7:
        raise ValueError('Expected base seven')
    transfer_index = {key: i for i, key in enumerate(sorted(data['certificates']))}
    out = '''-- Generated by research/ladder_layers/export_data.py; Lean must check every finite claim.
import Heraclitus.LadderLayers
import Heraclitus.TransferCatalogueData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.LadderLayersData
open LadderLayers

'''
    keys = []
    bottom_exponents = []
    for number, case in enumerate(data['cases']):
        keys.append(json.dumps(case['case'], sort_keys=True, separators=(',', ':')))
        bottom_exponents.append(case['J'])
        rows = case['rows']
        a, period = case['repeat_start'], case['repeat_period']
        last = a + period
        names = []
        for i, row in enumerate(rows):
            name = f'layer{number:02}_{i:02}'
            names.append(name)
            transfers = ', '.join(f'TransferCatalogue.row{transfer_index[key]:03}' for key in row['transfers'])
            out += f'def {name} : Layer := {{\n'
            out += f'  entrance := {finite(row["state"])}\n  output := {finite(row["output"])}\n'
            out += f'  steps := [{transfers}]\n  level := {row["level"]}\n'
            out += f'  sampleH := {row["h"]}\n  residue := {row["h"] % case["modulus"]} }}\n\n'
        nexts = [a if i == last - 1 else a + 1 if i == last else i + 1 for i in range(len(rows))]
        next_terms = ', '.join(f'(⟨{i}, by decide⟩ : Fin {len(rows)})' for i in nexts)
        out += f'def ladder{number:02} : Ladder := {{\n'
        out += f'  size := {len(rows)}\n'
        out += '  row := fun i => #[' + ', '.join(names) + '][i]\n'
        out += f'  next := fun i => #[{next_terms}][i]\n'
        out += f'  start := ⟨0, by decide⟩\n  initial := {finite(case["initial"])}\n'
        out += f'  modulus := {case["modulus"]}\n  transient := {a}\n  period := {period} }}\n'
        out += f'theorem ladder{number:02}_checked : ladder{number:02}.Claim := by decide\n'
        out += f'def checked{number:02} : CheckedLadder := ⟨ladder{number:02}, ladder{number:02}_checked⟩\n\n'
    out += 'def catalogue : List CheckedLadder := [' + ', '.join(f'checked{i:02}' for i in range(len(data['cases']))) + ']\n'
    out += 'def sourceKeys : List String := [' + ', '.join(json.dumps(k) for k in keys) + ']\n'
    out += 'def bottomExponents : List Nat := [' + ', '.join(str(j) for j in bottom_exponents) + ']\n'
    out += f'def sourceSha256 : String := "{hashlib.sha256(raw).hexdigest()}"\n'
    out += '''
theorem catalogue_complete : catalogue.length = 18 ∧ sourceKeys.length = 18 ∧
    sourceKeys.Nodup ∧ bottomExponents = List.replicate 18 4 := by decide

/-- Every supplied ladder map composes for every finite number of higher layers. -/
theorem all_heights : ∀ c ∈ catalogue, ∀ (anchor : Int) (levels : Nat),
    ∃ w : List Int,
      ValidWord (translate (anchor + 2401) (mark c.ladder.initial.toState (tower 2401 levels))) w ∧
      execute (translate (anchor + 2401) (mark c.ladder.initial.toState (tower 2401 levels))) w =
        translate (anchor + scale levels) (c.ladder.entry levels).toState ∧
      (w.length : Int) = scale levels - 2401 + c.ladder.cumulative 0 levels := by
  intro c _hc anchor levels
  exact c.ladder.from_bottom c.checked anchor levels

/-- The finite transient and period control every later phase, not just two samples. -/
theorem all_periods : ∀ c ∈ catalogue, ∀ n,
    c.ladder.orbit (c.ladder.transient + n + c.ladder.period) =
      c.ladder.orbit (c.ladder.transient + n) := by
  intro c _hc n
  exact c.ladder.periodic c.checked n

end Heraclitus.LadderLayersData
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--certificates', type=Path, default=ROOT / 'certificates')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--write', action='store_true')
    action.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(args.certificates)
    if args.write:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected)
        print('Wrote ladder layer data; kernel verification is required.')
    elif not args.output.is_file() or args.output.read_text() != expected:
        raise SystemExit('Ladder layer source binding mismatch')
    else:
        print('Ladder layer source binding matches (identity only, not a proof).')


if __name__ == '__main__':
    main()
