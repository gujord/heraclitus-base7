"""Bind the 35 post-ladder transfers to checked phase and transfer records.

The serializer chooses references; Lean checks phase closure, whole-state
equality and both modular premises. No producer/checker logic is imported.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIGNED = ROOT / 'certificates/signed-machine.json'
LADDER = ROOT / 'certificates/ladder-machine.json'
TARGET = ROOT / 'formal/Heraclitus/PostLadderData.lean'


def render(signed=SIGNED, ladder=LADDER):
    sr, lr = signed.read_bytes(), ladder.read_bytes()
    sd, ld = json.loads(sr), json.loads(lr)
    if sd['base'] != 7 or ld['base'] != 7 or [r['k'] for r in sd['transitions']] != list(range(40, 76)):
        raise ValueError('Expected all 36 base-seven phase labels')
    keys = [(c['case']['offset'], c['case']['core']) for c in ld['cases']]
    transfers = sorted(ld['certificates'])
    if len(keys) != 18 or len(transfers) != 119:
        raise ValueError('Expected 18 ladder inputs and 119 transfers')
    out = '''-- Generated by research/post_ladder/export_data.py; kernel checking is required.
import Heraclitus.PostLadder
import Heraclitus.SignedLadderData
import Heraclitus.SignedTransferData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.PostLadderData
open PostLadder OutgoingWord ReturnBridge

'''
    summary = []
    for r in sd['transitions']:
        k = r['k']
        if not r['anchor_used']:
            if k != 43:
                raise ValueError('Unexpected unused-anchor branch')
            continue
        if len(r['transfer_keys']) != 1:
            raise ValueError('Expected one post-ladder transfer')
        index = keys.index((r['core']['offset'], r['core']['core']))
        transfer = transfers.index(r['transfer_keys'][0])
        out += f'''def input{k} : Input := {{
  before := SignedLadderData.phase{k}
  ladder := LadderEnvelopeData.checked{index:02}
  matched := SignedBottomData.match{k}
  route_eq := rfl
  transfer := SignedTransferData.checked{transfer:03} }}
theorem input{k}_checked : input{k}.Claim := by decide
def checked{k} : Checked := ⟨input{k}, input{k}_checked⟩

'''
        summary.append({'label': k, 'ladder': index, 'transfer': transfer,
                        'key': r['transfer_keys'][0]})
    out += 'def catalogue : List Checked := [' + ', '.join(f'checked{r["label"]}' for r in summary) + ']\n'
    out += 'def signedSourceSha256 : String := "' + hashlib.sha256(sr).hexdigest() + '"\n'
    out += 'def ladderSourceSha256 : String := "' + hashlib.sha256(lr).hexdigest() + '"\n\n'
    out += '''theorem source_agrees : signedSourceSha256 = SignedLadderData.signedSourceSha256 ∧
    ladderSourceSha256 = SignedLadderData.ladderSourceSha256 := ⟨rfl, rfl⟩

theorem phases_agree : catalogue.map (fun c => c.input.before) =
    SignedLadderData.catalogue.filter (fun c => c.route.isLadder) := rfl

theorem labels_complete : catalogue.map (fun c => c.input.before.entrance.outgoing.row.label) =
    ((List.range 36).map (fun i => i+40)).filter (fun i => i != 43) := by decide

theorem all_inputs : ∀ c ∈ catalogue, ∀ t,
    c.input.before.endpoint t =
      ((SignedTransfer.start c.input.transfer.original.transfer
        (7^(c.input.before.exponent t) : Nat) [2*(7^(c.input.before.exponent t) : Nat)]).shift
          ((7^(c.input.before.exponent t) : Nat)+c.input.before.entrance.data.anchor)).toState ∧
    ((7^(c.input.before.exponent t) : Nat) : Int) % c.input.transfer.original.transfer.modulus =
      c.input.transfer.original.transfer.residue := by
  intro c _hc t
  exact ⟨c.input_all t, c.residue_all t⟩

theorem all_exponents : ∀ c ∈ catalogue, ∀ (t : Nat) (C : Int),
    2*C+1=(7^(c.input.before.exponent t) : Nat) →
    ∃ q r : Nat, ∃ b : SignedBlock (c.input.before.entrance.outgoing.inner.initial.toState C)
      (liftRay (!c.input.before.entrance.outgoing.row.positive) C
        (farBoundary c.input.before.entrance.outgoing q) (c.input.endpoint t)),
      (b.word.length : Int) = c.input.before.moves t q+c.input.transferMoves r ∧
      (7^(c.input.before.exponent t) : Nat) = c.input.transfer.original.transfer.target+
        (r : Int)*c.input.transfer.original.transfer.modulus ∧
      3*(7^(c.input.before.exponent t) : Nat)-200 ≤
        (farBoundary c.input.before.entrance.outgoing q).front ∧
      c.input.before.CycleIndex t q := by
  intro c _hc t C radius
  exact c.all_exponents t C radius

end Heraclitus.PostLadderData
'''
    return out, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--signed', type=Path, default=SIGNED)
    parser.add_argument('--ladder', type=Path, default=LADDER)
    args = parser.parse_args()
    text, rows = render(args.signed, args.ladder)
    if args.write:
        if args.signed.resolve() != SIGNED or args.ladder.resolve() != LADDER:
            raise SystemExit('Alternate sources cannot replace committed data')
        TARGET.write_text(text)
    elif TARGET.read_text() != text:
        raise SystemExit('Post-ladder source binding mismatch')
    print(f'PASS: {len(rows)} phase inputs bound to {len({r["transfer"] for r in rows})} transfer records')


if __name__ == '__main__':
    main()
