"""Bind finite first-crossing arithmetic to signed-machine.json.

This exporter is not a mathematical checker and imports no producer/checker
code. Lean checks the emitted threshold comparisons. The existing Python
checker separately validates the source routes and their physical context.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "certificates/signed-machine.json"
TARGET = REPO / "formal/Heraclitus/FirstCrossingData.lean"


def render(source=SOURCE):
    payload = source.read_bytes()
    data = json.loads(payload)
    rows = data["transitions"]
    if data["base"] != 7 or [r["k"] for r in rows] != list(range(40, 76)):
        raise ValueError("Expected exactly the 36 base-seven transition labels")
    lines = [
        "import Heraclitus.FirstCrossing", "", "set_option autoImplicit false",
        "set_option maxRecDepth 100000", "set_option maxHeartbeats 4000000", "",
        "/-! Generated by research/first_crossing/export_data.py.",
        "Source: certificates/signed-machine.json",
        "SHA-256: " + hashlib.sha256(payload).hexdigest(),
        "Only arithmetic premises are proved here. The source routes, physical",
        "candidate availability, and omitted-power exclusions are not formalized.",
        "All finite proofs use `decide`, not `native_decide` or external axioms.",
        "-/", "", "namespace Heraclitus.FirstCrossingData", "",
        "open Heraclitus.FirstCrossing", "",
    ]
    summary = []
    for row in rows:
        label = row["k"]
        cert = row["first_exit"]
        least = 6 + (label - 6) % 36
        m = 7**least
        period = len(cert["cycle"])
        if period != cert["modulus"] or period <= 0:
            raise ValueError("Cycle period does not match the finite word")
        if cert["sign"] not in (-1, 1):
            raise ValueError("Invalid sign")
        front = cert["initial_front"] + sum(edge[2] for edge in cert["prefix"])
        shift = 0
        phases = []
        for before, after, advance, choice in cert["cycle"]:
            u, w = shift + before[0], shift + choice
            rhs = 6*m + 1 - 2*front - u - w
            q = rhs // (2*period) + 1 if cert["sign"] > 0 else -((-rhs) // (2*period))
            phases.append((u, w, shift, q))
            shift += advance
        if shift != period:
            raise ValueError("Total cycle advance differs from its length")
        selected = cert["phase"]
        if not 0 <= selected < period:
            raise ValueError("Selected phase out of range")
        if phases[selected][0] - phases[selected][2] != cert["state"][0]:
            raise ValueError("Selected current differs from the certificate")
        lines.extend([
            f"def row{label} : Row where",
            f"  label := {label}", f"  leastExponent := {least}",
            "  positive := " + ("true" if cert["sign"] > 0 else "false"),
            f"  front := {front}", "  phases := #[",
        ])
        for i, (u, w, f, q) in enumerate(phases):
            lines.append(f"    ⟨{u}, {w}, {f}, {q}⟩" + ("," if i+1 < period else ""))
        lines.extend([
            "  ]", f"  selected := ⟨{selected}, by decide⟩",
            f"  expectedFront := {cert['front']}",
            f"  expectedEntry := {cert['entry']}", "",
            f"theorem row{label}_checked : row{label}.Checked := by decide", "",
        ])
        summary.append({"label": label, "least_exponent": least,
                        "period": period, "phase": selected,
                        "winning_cycle": phases[selected][3],
                        "sign": cert["sign"],
                        "equality_phases": sum(6*m+1-2*front-u-w == 2*period*q
                                               for u, w, _, q in phases)})
    lines.extend([
        "def catalogue : List {r : Row // r.Checked} := [",
        ",\n".join(f"  ⟨row{k}, row{k}_checked⟩" for k in range(40, 76)),
        "]", "",
        "theorem labels_complete : catalogue.map (fun r => r.val.label) =",
        "    (List.range 36).map (fun i => i + 40) := by decide", "",
        "end Heraclitus.FirstCrossingData",
    ])
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write the owned Lean data file")
    args = parser.parse_args()
    content, summary = render()
    if args.write:
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("FirstCrossingData.lean is not bound to the current JSON certificate")
    print(json.dumps({"status": "binding matches", "rows": len(summary),
                      "phase_comparisons": sum(r["period"] for r in summary),
                      "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest()}, indent=2))


if __name__ == "__main__":
    main()
