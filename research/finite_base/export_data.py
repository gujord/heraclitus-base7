"""Generate untrusted complete signed-base traces; Lean checks every hint."""
import argparse
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'formal/Heraclitus/FiniteBaseData'
ASSEMBLY = ROOT / 'formal/Heraclitus/FiniteBaseData.lean'
LIMIT = 7**6
CHUNK = 1024
EXPECTED = '3a9478e37859b92ba9e2a5d3a3cd1576cbba5071ceed829baae5d32b777d0c2c'
HEADER = '''-- Generated by research/finite_base/export_data.py; every state is untrusted.
import Heraclitus.FiniteBase
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 40000000
'''


def traces():
    used, current, radius, powers = {0}, 0, 0, [1]
    rays = {True: (1, []), False: (1, [])}
    digest = hashlib.sha256(struct.pack('<q', 0))

    def record():
        def ray(side):
            front, extras = rays[side]
            return f'⟨{front}, {extras}⟩'
        return f'⟨{str(current >= 0).lower()}, {abs(current)}, {ray(True)}, {ray(False)}⟩'

    initial, states, pieces = record(), [], []
    for index in range(1, LIMIT+1):
        while powers[-1] <= 2*radius:
            powers.append(7*powers[-1])
        current = min((current+side*power for power in powers for side in [-1, 1]
                       if current+side*power not in used), key=lambda x: (abs(x), -x))
        used.add(current)
        side, value = current > 0, abs(current)
        front, extra = rays[side]
        while (front if side else -front) in used:
            front += 1
        rays[side] = front, [x for x in [value, *extra] if x >= front]
        radius = max(radius, value)
        digest.update(struct.pack('<q', current))
        final = record()
        states.append(final)
        if index % CHUNK == 0 or index == LIMIT:
            pieces.append((initial, states, final))
            initial, states = final, []
    if digest.hexdigest() != EXPECTED:
        raise ValueError('Generated prefix differs from the original finite-base digest')
    return pieces


def render():
    pieces = traces()
    outputs = {}
    for i, (initial, states, final) in enumerate(pieces):
        name = f'Case{i:03}'
        text = HEADER+f'\nnamespace Heraclitus.FiniteBaseData.{name}\nopen FiniteBase SignedCertificate\n\n'
        text += f'def initial : Record := {initial}\ndef final : Record := {final}\n'
        text += 'def states : List Record := [\n  '+',\n  '.join(states)+']\n'
        text += '''
theorem checked : traceCheck initial states=true := by decide +kernel
theorem closed : traceEnd initial states=final := rfl
def chunk : CheckedTrace := ⟨initial, final, states, checked, closed⟩
'''
        text += f'theorem length : chunk.block.word.length={len(states)} := by\n  rw [CheckedTrace.length]\n  decide\n\nend Heraclitus.FiniteBaseData.{name}\n'
        outputs[DEST / (name+'.lean')] = text
    text = '-- Generated by research/finite_base/export_data.py; full base assembly.\n'
    text += '\n'.join(f'import Heraclitus.FiniteBaseData.Case{i:03}' for i in range(len(pieces)))+'\n'
    text += '''import Heraclitus.SignedBoundaryData
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 40000000
namespace Heraclitus.FiniteBaseData
open FiniteBase SignedCertificate

'''
    total = 0
    for i, (_, states, _) in enumerate(pieces):
        total += len(states)
        start = 'Case000.initial.toState 0'
        end = f'Case{i:03}.final.toState 0'
        expression = f'Case{i:03}.chunk.block' if i == 0 else f'part{i-1:03}.then Case{i:03}.chunk.block'
        text += f'def part{i:03} : SignedBlock ({start}) ({end}) := {expression}\n'
        if i == 0:
            text += f'theorem count{i:03} : part{i:03}.word.length={total} := Case{i:03}.length\n\n'
        else:
            text += f'''theorem count{i:03} : part{i:03}.word.length={total} := by
  change (part{i-1:03}.word ++ Case{i:03}.chunk.block.word).length=_
  rw [List.length_append, count{i-1:03}, Case{i:03}.length]
\n'''
    last = len(pieces)-1
    text += f'''theorem initial_exact : Case000.initial.toState 0=signedStart := FiniteBase.initial_exact

theorem final_exact : Case{last:03}.final.toState 0=SignedBoundaryData.row42_inner.initial.toState 58824 := by
  apply state_ext
  · rfl
  · intro x
    change (x=0 ∨ (0<x ∧ (x-0<58826 ∨ x-0 ∈ ([] : List Int))) ∨
      (x<0 ∧ (-x-0<58822 ∨ -x-0 ∈ [58823, 58824, 58826]))) ↔
      (x=0 ∨ (0<x ∧ (x-58824<2 ∨ x-58824 ∈ ([] : List Int))) ∨
      (x<0 ∧ (-x-58824< -2 ∨ -x-58824 ∈ [-1, 0, 2])))
    simp only [List.mem_cons, List.not_mem_nil, or_false]
    omega

def base : SignedBlock signedStart (SignedBoundaryData.row42_inner.initial.toState 58824) where
  word := part{last:03}.word
  valid := by rw [← initial_exact]; exact part{last:03}.valid
  endpoint := by rw [← initial_exact]; exact part{last:03}.endpoint.trans final_exact

theorem base_length : base.word.length=7^6 := count{last:03}

theorem base_valid : SignedValidWord signedStart base.word := base.valid

theorem base_endpoint : execute signedStart base.word=
    SignedBoundaryData.row42_inner.initial.toState 58824 := base.endpoint

end Heraclitus.FiniteBaseData
'''
    outputs[ASSEMBLY] = text
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    outputs = render()
    expected = {p.name for p in outputs if p.parent == DEST}
    if DEST.exists() and {p.name for p in DEST.glob('*.lean')}-expected:
        raise SystemExit('Unexpected generated base source file')
    for path, text in outputs.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            raise SystemExit('Finite-base generated-source mismatch: '+str(path))
    print(f'PASS: {len(outputs)-1} complete trace chunks and assembly match generation; {LIMIT} moves')


if __name__ == '__main__':
    main()
