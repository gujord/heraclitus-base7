"""Bind the 36 phase routes to existing checked matches and ladder envelopes.

This untrusted serializer imports neither producer nor checker logic.
Lean checks exact catalogue identities and the proof-carrying route types.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIGNED = ROOT / 'certificates/signed-machine.json'
LADDER = ROOT / 'certificates/ladder-machine.json'
TARGET = ROOT / 'formal/Heraclitus/SignedLadderData.lean'


def render(signed=SIGNED, ladder=LADDER):
    sr, lr = signed.read_bytes(), ladder.read_bytes()
    sd, ld = json.loads(sr), json.loads(lr)
    rows, cases = sd['transitions'], ld['cases']
    if sd['base'] != 7 or ld['base'] != 7 or [r['k'] for r in rows] != list(range(40, 76)):
        raise ValueError('Expected all 36 base-seven phase labels')
    keys = [(c['case']['offset'], c['case']['core']) for c in cases]
    if len(keys) != 18 or len({json.dumps(k) for k in keys}) != 18:
        raise ValueError('Expected 18 distinct ladder inputs')
    out = '''-- Generated by research/signed_ladder/export_data.py; kernel checking is required.
import Heraclitus.SignedLadder
import Heraclitus.SignedBottomData
import Heraclitus.LadderEnvelopeData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.SignedLadderData
open SignedLadder OutgoingWord ReturnBridge

'''
    for row in rows:
        label = row['k']
        if row['anchor_used']:
            i = keys.index((row['core']['offset'], row['core']['core']))
            route = f'.ladder LadderEnvelopeData.checked{i:02} SignedBottomData.match{label}'
        else:
            if label != 43:
                raise ValueError('Unexpected short branch')
            route = '.short SignedBottomData.match43'
        out += f'def phase{label} : Phase := ⟨ReturnBridgeData.entrance{label}, {route}⟩\n'
    out += '\ndef catalogue : List Phase := [' + ', '.join(f'phase{k}' for k in range(40, 76)) + ']\n'
    out += 'def signedSourceSha256 : String := "' + hashlib.sha256(sr).hexdigest() + '"\n'
    out += 'def ladderSourceSha256 : String := "' + hashlib.sha256(lr).hexdigest() + '"\n\n'
    out += '''theorem ladder_source_agrees : ladderSourceSha256 = LadderEnvelopeData.sourceSha256 := rfl

theorem entrances_agree : catalogue.map (fun c => c.entrance) =
    ReturnBridgeData.catalogue := rfl

theorem labels_complete : catalogue.map (fun c => c.entrance.outgoing.row.label) =
    (List.range 36).map (fun i => i+40) := by decide

theorem branches_complete :
    ((catalogue.filter (fun c => c.route.isLadder)).length = 35) ∧
    (catalogue.filter (fun c => !c.route.isLadder)).map
      (fun c => c.entrance.outgoing.row.label) = [43] := by decide

theorem used_entrances_agree : (catalogue.filter (fun c => c.route.isLadder)).map
    (fun c => c.entrance) = SignedBottomData.catalogue.map (fun c => c.entrance) := rfl

/-- All 36 routes, with full signed endpoints, exact word counts and the
outgoing cycle-index relation retained for subsequent scale assembly. -/
theorem all_exponents : ∀ c ∈ catalogue, ∀ (t : Nat) (C : Int),
    2*C+1 = (7^(c.exponent t) : Nat) →
    ∃ q : Nat, ∃ b : SignedBlock (c.entrance.outgoing.inner.initial.toState C)
      (liftRay (!c.entrance.outgoing.row.positive) C (farBoundary c.entrance.outgoing q)
        (c.endpoint t)),
      (b.word.length : Int) = c.moves t q ∧
      3*(7^(c.exponent t) : Nat)-200 ≤ (farBoundary c.entrance.outgoing q).front ∧
      c.CycleIndex t q := by
  intro c _hc t C radius
  exact c.all_exponents t C radius

end Heraclitus.SignedLadderData
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--signed', type=Path, default=SIGNED)
    parser.add_argument('--ladder', type=Path, default=LADDER)
    args = parser.parse_args()
    text = render(args.signed, args.ladder)
    if args.write:
        if args.signed.resolve() != SIGNED or args.ladder.resolve() != LADDER:
            raise SystemExit('Alternate sources cannot replace committed data')
        TARGET.write_text(text)
    elif TARGET.read_text() != text:
        raise SystemExit('Signed ladder source binding mismatch')
    print('PASS: 36 routes match both certificate identities and existing proof records')


if __name__ == '__main__':
    main()
