"""Bind the 36 complete transition records to their successive exponent order."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'formal/Heraclitus/ScaleScheduleData.lean'
ORDER = list(range(42,76))+[40,41]


def render():
    text = '''-- Generated by research/scale_schedule/export_data.py; every link is proved.
import Heraclitus.ScaleSchedule
import Heraclitus.OuterBoundaryData
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 40000000
namespace Heraclitus.ScaleScheduleData
open ScaleSchedule OuterBoundary

def entry (i : Fin 36) : Transition := match i.val with
'''
    for i,label in enumerate(ORDER):
        text += f'  | {i if i<35 else "_"} => OuterBoundaryData.transition{label}\n'
    text += '''
theorem least (i : Fin 36) : (entry i).checked.link.approach.row.leastExponent=i.val+6 := by
  have all : ∀ i : Fin 36, (entry i).checked.link.approach.row.leastExponent=i.val+6 := by decide
  exact all i

theorem follows (i : Fin 36) : (entry i).checked.link.following=
    (entry (nextIndex i)).checked.link.phase.entrance.outgoing.inner.initial := by
  obtain ⟨i, bound⟩ := i
'''
    text += '  have cases : '+ ' ∨ '.join(f'i={i}' for i in range(36))+' := by omega\n'
    text += '  rcases cases with '+ ' | '.join('rfl' for _ in range(36))+'\n'
    text += '''  all_goals (simp [entry, nextIndex] <;> rfl)

def schedule : Schedule := ⟨entry, least, follows⟩

theorem initial_boundary : schedule.boundary 0=SignedBoundaryData.row42_inner.initial.toState 58824 := rfl

theorem first_class : (entry ⟨0, by decide⟩).checked.link.approach.row.label=42 := rfl

theorem last_class : (entry ⟨35, by decide⟩).checked.link.approach.row.label=41 := rfl

end Heraclitus.ScaleScheduleData
'''
    return text


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    parser.add_argument('--target',type=Path,default=TARGET)
    args=parser.parse_args();text=render()
    if args.write:
        if args.target.resolve()!=TARGET:raise SystemExit('Alternate targets are check-only')
        TARGET.write_text(text)
    elif args.target.read_text()!=text:
        raise SystemExit('Scale-schedule generated-source mismatch')
    print('PASS: all 36 successive exponent classes match the generated schedule')


if __name__=='__main__':main()
