def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--target', type=Path, default=TARGET)
    args = parser.parse_args()
    text = render()
    if args.write:
        if args.target.resolve() != TARGET:
            raise SystemExit('Alternate targets are check-only')
        TARGET.write_text(text)
    elif args.target.read_text() != text:
        raise SystemExit('Outer-boundary generated-source mismatch')
    print('PASS: 36 outer-boundary links and phase compositions match their generator')


if __name__ == '__main__':
    main()
