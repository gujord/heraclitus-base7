"""Bind all 18 existing bottom records to complete-used-set bounds.

No producer/checker imports or mathematical validation occurs here.
Lean checks every phase-row front and every explicitly used point.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'formal/Heraclitus/LadderEnvelopeData.lean'
SOURCE = ROOT / 'certificates/ladder-machine.json'


def render(source=SOURCE):
    raw = source.read_bytes()
    data = json.loads(raw)
    if data['base'] != 7 or len(data['cases']) != 18:
        raise ValueError('Expected the 18 base-seven ladder cases')
    out = '''-- Generated by research/ladder_envelope/export_data.py; kernel checking is required.
import Heraclitus.LadderEnvelope
import Heraclitus.LadderBottomData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.LadderEnvelopeData
open LadderEnvelope Outgoing OutgoingWord

'''
    for i in range(len(data['cases'])):
        out += f'''theorem bounded{i:02} : Bounded LadderBottomData.bottom{i:02} := by decide
def checked{i:02} : Checked := ⟨LadderBottomData.checkedBottom{i:02}, bounded{i:02}⟩

'''
    out += 'def catalogue : List Checked := [' + ', '.join(f'checked{i:02}' for i in range(18)) + ']\n'
    out += 'def sourceSha256 : String := "' + hashlib.sha256(raw).hexdigest() + '"\n\n'
    out += '''theorem source_agrees : sourceSha256 = LadderBottomData.sourceSha256 := rfl

theorem catalogue_agrees : catalogue.map (fun c => c.original) =
    LadderBottomData.catalogue := rfl

theorem catalogue_complete : catalogue.length = 18 ∧
    (catalogue.map (fun c => c.original.bottom.ladder.ladder.size)).sum = 129 := by decide

/-- Every phase row is checked, including rows not selected at a sampled height. -/
theorem all_bounds : ∀ c ∈ catalogue, Bounded c.original.bottom := by
  intro c _hc
  exact c.bounded

theorem all_heights : ∀ c ∈ catalogue, ∀ n,
    ∃ w : List Int,
      ValidWord (c.initial n).toState w ∧
      execute (c.initial n).toState w = c.output n ∧
      (w.length : Int) = c.moves n ∧
      ReturnBridge.Envelope (LadderLayers.scale n) (c.initial n).toState w := by
  intro c _hc n
  exact c.halfline_all_heights n

theorem all_signed_heights : ∀ c ∈ catalogue, ∀ n, 2 ≤ n →
    ∀ (side : Bool) (C : Int) (other : RayBoundary),
      2*C+1 = LadderLayers.scale n →
      3*LadderLayers.scale n-200 ≤ other.front →
    ∃ w : List Int,
      SignedValidWord (liftRay side C other (c.initial n).toState) w ∧
      execute (liftRay side C other (c.initial n).toState) w =
        liftRay side C other (c.output n) ∧
      (w.length : Int) = c.moves n := by
  intro c _hc n height side C other radius filled
  exact c.signed_all_heights n side C other radius (scale_sufficient n height) filled

end Heraclitus.LadderEnvelopeData
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=SOURCE)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    text = render(args.source)
    if args.write:
        TARGET.write_text(text)
        print('Wrote ' + str(TARGET.relative_to(ROOT)))
    elif TARGET.read_text() != text:
        raise SystemExit('Ladder envelope source binding mismatch')
    else:
        print('PASS: all 18 ladder envelope records match their source identity')


if __name__ == '__main__':
    main()
