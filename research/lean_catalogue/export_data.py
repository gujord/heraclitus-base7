"""Serialize the full marker catalogue as untrusted Lean data and finite proofs.

No generator or Python checker logic is imported. Lean must check every
emitted proof. --check compares bytes without writing; --write regenerates.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = 'ladder-machine.json'
BASE = Path('formal/Heraclitus/TransferCatalogue')
MAIN = Path('formal/Heraclitus/TransferCatalogueData.lean')


def state_key(s):
    return s[0], tuple(s[1])


def edge_key(e):
    return state_key(e[0]), state_key(e[1]), e[2], e[3]


def integers(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def word(edges, front):
    result = []
    for _s, _t, shift, choice in edges:
        result.append(front + choice)
        front += shift
    return result, front


def preamble(imports):
    return ('-- Generated by research/lean_catalogue/export_data.py; kernel checking is required.\n' +
            ''.join('import ' + name + '\n' for name in imports) +
            '\nset_option autoImplicit false\nset_option maxRecDepth 10000\n' +
            'set_option maxHeartbeats 4000000\n\n' +
            'namespace Heraclitus.TransferCatalogue\nopen TransferCertificate\n\n')


def render(certificate_dir):
    raw = (certificate_dir / SOURCE).read_bytes()
    data = json.loads(raw)
    if data['base'] != 7:
        raise ValueError('Expected base seven')
    records = sorted(data['certificates'].items())
    edges = sorted({edge_key(e) for _, c in records for part in ['prefix', 'cycle', 'repair'] for e in c[part]})
    nodes = sorted({s for e in edges for s in e[:2]} |
                   {state_key(c['initial'][1:]) for _, c in records})
    ni = {s: 'node' + str(i) for i, s in enumerate(nodes)}
    ei = {e: 'edge' + str(i) for i, e in enumerate(edges)}
    files = {}
    end = '\nend Heraclitus.TransferCatalogue\n'
    text = preamble(['Heraclitus.TransferCertificate'])
    for s in nodes:
        text += f'def {ni[s]} : Node := ⟨{s[0]}, {integers(s[1])}⟩\n'
    files[BASE / 'Nodes.lean'] = text + end
    edge_modules = []
    for first in range(0, len(edges), 100):
        module = f'Edges{first // 100:02}'
        edge_modules.append('Heraclitus.TransferCatalogue.' + module)
        text = preamble(['Heraclitus.TransferCatalogue.Nodes'])
        for e in edges[first:first + 100]:
            s, t, shift, choice = e
            text += f'def {ei[e]} : CheckedEdge := ⟨⟨{ni[s]}, {ni[t]}, {shift}, {choice}⟩, by decide⟩\n'
        files[BASE / (module + '.lean')] = text + end
    files[BASE / 'Edges.lean'] = ''.join('import ' + name + '\n' for name in edge_modules)

    def route(initial, entries):
        refs = ', '.join(ei[edge_key(e)] for e in entries)
        return f'⟨{ni[state_key(initial)]}, [{refs}], by decide⟩'

    row_modules = []
    row_names = []
    for first in range(0, len(records), 10):
        module = f'Rows{first // 10:02}'
        row_modules.append('Heraclitus.TransferCatalogue.' + module)
        text = preamble(['Heraclitus.TransferCatalogue.Edges'])
        for index, (key, c) in enumerate(records[first:first + 10], first):
            name = f'row{index:03}'
            row_names.append(name)
            f, cur, points = c['initial']
            _prefix_word, entry_front = word(c['prefix'], f)
            cycle_word, _ = word(c['cycle'], entry_front)
            phase = c['phase']
            target = cycle_word[phase]
            phase_front = entry_front + sum(e[2] for e in c['cycle'][:phase])
            pc, pb = c['cycle'][phase][0]
            marked = set(pb) | {target - phase_front}
            shift = 0
            while shift in marked:
                shift += 1
            repair_start = [pc - shift, sorted(x - shift for x in marked if x >= shift)]
            repair_front = phase_front - target + shift
            of, oc, op = c['output']
            text += f'-- Source key: {key}\ndef {name} : CheckedTransfer := {{\n'
            text += '  transfer := {\n'
            text += f'    initialFront := {f}\n'
            text += f'    transient := {route([cur, points], c["prefix"])}\n'
            text += f'    cycle := {route(c["cycle"][0][0], c["cycle"])}\n'
            text += f'    before := {route(c["cycle"][0][0], c["cycle"][:phase])}\n'
            text += f'    phase := {phase}\n    target := {target}\n'
            text += f'    after := {integers(cycle_word[phase + 1:])}\n'
            text += f'    modulus := {c["modulus"]}\n    residue := {c["residue"]}\n'
            text += f'    repairFront := {repair_front}\n'
            text += f'    repair := {route(repair_start, c["repair"])}\n'
            text += f'    output := ⟨{of + oc}, {of}, {integers([of + x for x in op])}⟩ }}\n'
            text += '  checked := by decide }\n\n'
        files[BASE / (module + '.lean')] = text + end
    text = preamble(row_modules)
    text += f'def sourceSha256 : String := "{hashlib.sha256(raw).hexdigest()}"\n'
    text += 'def keys : List String := [' + ', '.join(json.dumps(k) for k, _ in records) + ']\n'
    text += 'def catalogue : List CheckedTransfer := [' + ', '.join(row_names) + ']\n'
    text += 'theorem catalogue_size : catalogue.length = 119 := by decide\n'
    text += 'theorem keys_size : keys.length = catalogue.length := by decide\n'
    text += 'theorem keys_distinct : keys.Nodup := by decide\n'
    text += '''
/-- Every source-bound catalogue entry has a valid uniform transfer, with exact count and full endpoint. -/
theorem catalogue_uniform : ∀ c ∈ catalogue, ∀ (h : Int) (later : Int → Prop),
    2401 ≤ h → h % (c.transfer.modulus : Int) = c.transfer.residue →
    (∀ x, later x → 2 * h ≤ x) → c.transfer.Result h later := by
  intro c _hc h later large residue later_bound
  exact c.transfer.complete c.checked h later large residue later_bound
'''
    files[MAIN] = text + end
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--certificates', type=Path, default=ROOT / 'certificates')
    parser.add_argument('--root', type=Path, default=ROOT)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--write', action='store_true')
    action.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render(args.certificates)
    for relative, expected in files.items():
        path = args.root / relative
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif not path.is_file() or path.read_text() != expected:
            raise SystemExit('Catalogue source binding mismatch: ' + str(relative))
    print(f'{"Wrote" if args.write else "Matched"} {len(files)} Lean source files; data binding is not a mathematical proof.')


if __name__ == '__main__':
    main()
