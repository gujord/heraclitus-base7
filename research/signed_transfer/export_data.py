"""Bind finite signed-transfer bounds to all 119 existing checked records.

This is untrusted serialization. Every bound is proved by Lean; no
mathematical producer or checker is imported.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "certificates/ladder-machine.json"
TARGET = REPO / "formal/Heraclitus/SignedTransferData.lean"


def render(source=SOURCE):
    raw = source.read_bytes()
    data = json.loads(raw)
    records = sorted(data["certificates"].items())
    if data["base"] != 7 or len(records) != 119:
        raise ValueError("Expected all 119 base-seven transfers")
    lines = ["import Heraclitus.SignedTransfer", "import Heraclitus.TransferCatalogueData", "",
             "set_option autoImplicit false", "set_option maxRecDepth 100000", "",
             "/-! Generated by research/signed_transfer/export_data.py.",
             "Source SHA-256: " + hashlib.sha256(raw).hexdigest(), "-/", "",
             "namespace Heraclitus.SignedTransferData", "open SignedTransfer TransferCatalogue OutgoingWord", ""]
    summary = []
    for i, (key, c) in enumerate(records):
        lines += [f"theorem bounds{i:03d} : Bounds row{i:03d}.transfer := by decide",
                  f"def checked{i:03d} : Checked := ⟨row{i:03d}, bounds{i:03d}⟩", ""]
        f, current, _points = c["initial"]
        of, _oc, op = c["output"]
        summary.append({"row": i, "key": key, "initial_front": f, "initial_current": f+current,
                        "output_front": of, "output_points": [of+x for x in op]})
    lines += ["def catalogue : List Checked := [" + ", ".join(f"checked{i:03d}" for i in range(119)) + "]", "",
              "theorem catalogue_agrees : catalogue.map (fun c => c.original) = TransferCatalogue.catalogue := rfl", "",
              "theorem catalogue_complete : catalogue.length=119 := by decide", "",
              "theorem all_bounds : ∀ c ∈ catalogue, Bounds c.original.transfer := by",
              "  intro c _hc", "  exact c.bounds", "",
              "theorem all_signed : ∀ c ∈ catalogue, ∀ (k : Nat) (C d h : Int) (later : List Int)",
              "    (side : Bool) (other : RayBoundary),",
              "    2*C+1=(7^k : Nat) → 100000 ≤ (7^k : Nat) → 2401 ≤ h →",
              "    h % (c.original.transfer.modulus : Int)=c.original.transfer.residue →",
              "    (∀ x ∈ later, 2*h ≤ x) → 0 ≤ d → d+h ≤ 2*((7^k : Nat) : Int)+3 →",
              "    3*(7^k : Nat)-200 ≤ other.front →",
              "    ∃ q : Nat, ∃ b : SignedBlock",
              "      (liftRay side C other ((start c.original.transfer h later).shift d).toState)",
              "      (liftRay side C other (translate d (endpoint c.original.transfer h later))),",
              "      h=c.original.transfer.target+(q : Int)*c.original.transfer.modulus ∧",
              "      b.word.length=c.original.transfer.transient.edges.length+c.original.transfer.modulus*q+",
              "        c.original.transfer.phase+c.original.transfer.repair.edges.length := by",
              "  intro c _hc k C d h later side other radius scaleLarge spacingLarge residue far nonnegative targetBound filled",
              "  exact c.signed k C d h later side other radius scaleLarge spacingLarge residue far nonnegative targetBound filled", "",
              "end Heraclitus.SignedTransferData"]
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--source", type=Path, default=SOURCE)
    args = parser.parse_args()
    content, records = render(args.source)
    if args.write:
        if args.source.resolve() != SOURCE.resolve():
            raise SystemExit("Alternate sources cannot replace committed data")
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("Signed transfer source binding mismatch")
    print(json.dumps({"status": "binding matches", "records": len(records)}, indent=2))


if __name__ == "__main__":
    main()
