"""Serialize the 18 old regions and anchors as untrusted Lean data.

This binds the forced-descent premises, not the finite bottom words.
The default action is --check. No generator/checker imports are used.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'formal/Heraclitus/LadderDescentData.lean'


def render(certificate_dir):
    raw = (certificate_dir / 'ladder-machine.json').read_bytes()
    data = json.loads(raw)
    if data['base'] != 7:
        raise ValueError('Expected base seven')
    out = '''-- Generated by research/ladder_descent/export_data.py; finite premises are checked by Lean.
import Heraclitus.LadderDescent

set_option autoImplicit false
set_option maxRecDepth 10000

namespace Heraclitus.LadderDescentData
open LadderDescent

'''
    keys = []
    labels = []
    for i, case in enumerate(data['cases']):
        entry = case['case']
        keys.append(json.dumps(entry, sort_keys=True, separators=(',', ':')))
        labels.append(case['J'])
        points = ', '.join(map(str, entry['core']))
        out += f'def entrance{i:02} : Entrance := ⟨{entry["offset"]}, [{points}]⟩\n'
        out += f'theorem entrance{i:02}_checked : entrance{i:02}.Claim := by decide\n'
        out += f'def checked{i:02} : CheckedEntrance := ⟨entrance{i:02}, entrance{i:02}_checked⟩\n\n'
    out += 'def catalogue : List CheckedEntrance := [' + ', '.join(f'checked{i:02}' for i in range(len(data['cases']))) + ']\n'
    out += 'def sourceKeys : List String := [' + ', '.join(json.dumps(k) for k in keys) + ']\n'
    out += 'def bottomExponents : List Nat := [' + ', '.join(map(str, labels)) + ']\n'
    out += f'def sourceSha256 : String := "{hashlib.sha256(raw).hexdigest()}"\n'
    out += '''
theorem catalogue_complete : catalogue.length = 18 ∧ sourceKeys.length = 18 ∧
    sourceKeys.Nodup ∧ bottomExponents = List.replicate 18 4 := by decide

/-- All 18 source configurations descend at every height, creating the exact tower. -/
theorem all_heights : ∀ c ∈ catalogue, ∀ n,
    ValidWord (c.entrance.initial n) ((word 4 n).map (fun x => x+c.entrance.anchor)) ∧
      execute (c.entrance.initial n) ((word 4 n).map (fun x => x+c.entrance.anchor)) =
        c.entrance.endpoint n ∧
      ((word 4 n).map (fun x => x+c.entrance.anchor)).length = 6*n := by
  intro c _hc n
  exact c.entrance.descend c.checked n

end Heraclitus.LadderDescentData
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--certificates', type=Path, default=ROOT / 'certificates')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--write', action='store_true')
    action.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(args.certificates)
    if args.write:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected)
        print('Wrote', args.output)
    elif args.output.read_text() != expected:
        raise SystemExit('Ladder descent source binding mismatch')
    else:
        print('Ladder descent source binding matched (identity only).')


if __name__ == '__main__':
    main()
