"""Render explicit signed approach compositions using already checked rows.

No new JSON data or mathematical truth is inferred by this serializer.
Lean must prove each concrete input match, endpoint and count.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'formal/Heraclitus/SignedApproachData.lean'


def render():
    parts = ['''-- Generated by research/signed_approach/export_data.py; Lean checking is required.
import Heraclitus.SignedApproach
import Heraclitus.ApproachWordData

set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 10000000

namespace Heraclitus.SignedApproachData
open OutgoingWord ReturnBridge SignedApproach

def catalogue : List ApproachWord.Checked := ApproachWordData.catalogue

theorem labels_complete : catalogue.map (fun c => c.row.label) =
    (List.range 36).map (fun i => i+40) := ApproachWordData.labels_complete

theorem all_exponents : ∀ c ∈ catalogue, ∀ (t : Nat) (C : Int)
    (side : Bool) (other : RayBoundary),
    2*C+1=(7^(c.row.exponent t) : Nat) → 3*c.row.scale t-200 ≤ other.front →
    ∃ b : SignedBlock (liftRay side C other (c.row.start (c.row.scale t)))
      (liftRay side C other (c.row.finish (c.row.scale t))),
      b.word=(c.row.word (c.row.scale t)).map (embedRay side C) ∧
      (b.word.length : Int)=c.row.moves (c.row.scale t) := by
  intro c _hc t C side other radius filled
  exact SignedApproach.all_exponents c t C side other radius filled
''']
    for label in range(40, 76):
        row = f'ApproachWordData.row{label}'
        checked = f'ApproachWordData.checked{label}'
        if label == 43:
            parts.append(f'''
/-- Exceptional phase 43: both concrete transfers followed by its entire approach. -/
theorem phase43 (t : Nat) (C : Int)
    (radius : 2*C+1=(7^({row}.exponent t) : Nat)) :
    ∃ q : Nat, ∃ b : SignedBlock
      (ShortReturnData.phase.entrance.outgoing.inner.initial.toState C)
      (liftRay true C (farBoundary ShortReturnData.phase.entrance.outgoing q)
        ({row}.finish ({row}.scale t))),
      (b.word.length : Int)=5*{row}.scale t+2+{row}.moves ({row}.scale t) ∧
      3*{row}.scale t-200 ≤ (farBoundary ShortReturnData.phase.entrance.outgoing q).front ∧
      ShortReturnData.phase.CycleIndex t q := by
  obtain ⟨q, first, count, filled, index⟩ := ShortReturnData.all_exponents t C radius
  have last := SignedApproach.all_exponents {checked} t C true
    (farBoundary ShortReturnData.phase.entrance.outgoing q) radius filled
  obtain ⟨last, _word, lastCount⟩ := last
  let tail := alignInput last (congrArg
    (liftRay true C (farBoundary ShortReturnData.phase.entrance.outgoing q))
    (ApproachWordData.input43_all t))
  refine ⟨q, first.then tail, ?_, filled, index⟩
  change (((first.word ++ last.word).length : Nat) : Int)=_
  rw [List.length_append, Int.natCast_add, count, lastCount]
  rfl
''')
        else:
            inp = f'PostLadderData.input{label}'
            parts.append(f'''
/-- Whole-state composition for phase {label}, at every exponent in its class. -/
theorem phase{label} (t : Nat) (C : Int)
    (radius : 2*C+1=(7^({row}.exponent t) : Nat)) :
    ∃ q r : Nat, ∃ b : SignedBlock
      ({inp}.before.entrance.outgoing.inner.initial.toState C)
      (liftRay (!{inp}.before.entrance.outgoing.row.positive) C
        (farBoundary {inp}.before.entrance.outgoing q)
        ({row}.finish ({row}.scale t))),
      (b.word.length : Int)={inp}.before.moves t q+{inp}.transferMoves r+
        {row}.moves ({row}.scale t) ∧
      {row}.scale t={inp}.transfer.original.transfer.target+
        (r : Int)*{inp}.transfer.original.transfer.modulus ∧
      3*{row}.scale t-200 ≤ (farBoundary {inp}.before.entrance.outgoing q).front ∧
      {inp}.before.CycleIndex t q := by
  obtain ⟨q, r, first, count, spacing, filled, index⟩ :=
    PostLadderData.checked{label}.all_exponents t C radius
  have last := SignedApproach.all_exponents {checked} t C
    (!{inp}.before.entrance.outgoing.row.positive)
    (farBoundary {inp}.before.entrance.outgoing q) radius filled
  obtain ⟨last, _word, lastCount⟩ := last
  let tail := alignInput last (congrArg
    (liftRay (!{inp}.before.entrance.outgoing.row.positive) C
      (farBoundary {inp}.before.entrance.outgoing q)) (ApproachWordData.input{label}_all t))
  refine ⟨q, r, first.then tail, ?_, spacing, filled, index⟩
  change (((first.word ++ last.word).length : Nat) : Int)=_
  rw [List.length_append, Int.natCast_add, count, lastCount]
  rfl
''')
    parts.append('\nend Heraclitus.SignedApproachData\n')
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--target', type=Path, default=TARGET)
    args = parser.parse_args()
    text = render()
    if args.write:
        if args.target.resolve() != TARGET:
            raise SystemExit('Alternate targets are check-only')
        TARGET.write_text(text)
    elif args.target.read_text() != text:
        raise SystemExit('Signed-approach generated-source mismatch')
    print('PASS: 36 explicit signed approach compositions match their generator')


if __name__ == '__main__':
    main()
