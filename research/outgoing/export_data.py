"""Extract outgoing geometry from the fixed signed certificate.

This is a data binding tool. Lean proves its finite propositions. No
producer or mathematical checker functions are imported here.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "certificates/signed-machine.json"
TARGET = REPO / "formal/Heraclitus/OutgoingData.lean"


def render():
    payload = SOURCE.read_bytes()
    data = json.loads(payload)
    rows = data["transitions"]
    if data["base"] != 7 or [r["k"] for r in rows] != list(range(40, 76)):
        raise ValueError("Expected base seven and exactly labels 40..75")
    lines = [
        "import Heraclitus.Outgoing", "import Heraclitus.FirstCrossingData", "",
        "set_option autoImplicit false", "set_option maxRecDepth 100000", "",
        "/-! Generated by research/outgoing/export_data.py.",
        "Source: certificates/signed-machine.json",
        "SHA-256: " + hashlib.sha256(payload).hexdigest(),
        "Only finite geometry is proved here. Reachability and the half-line",
        "cycle's complete physical semantics remain separate obligations.",
        "-/", "", "namespace Heraclitus.OutgoingData", "",
        "open Heraclitus Outgoing FirstCrossingData", "",
    ]
    summary = []
    for row in rows:
        k = row["k"]
        c = row["first_exit"]
        other = row["inner"]["sides"][str(-c["sign"])]
        front, extra = other
        shift = c["initial_front"]
        transient = []
        for before, after, advance, choice in c["prefix"]:
            transient.append((shift + before[0], shift + choice))
            shift += advance
        cycle_front = shift
        lower, reflected = [], []
        for before, after, advance, choice in c["cycle"]:
            lower.extend([shift + before[0], shift + choice])
            reflected.append(front - (1 - shift - before[0]))
            shift += advance
        lines.extend([
            f"def geometry{k} : GeometryData row{k} where",
            f"  other := ⟨{front}, [{', '.join(map(str, extra))}]⟩",
            "  transient := #[" + ", ".join(f"({u}, {w})" for u, w in transient) + "]",
            "", f"theorem geometry{k}_checked : geometry{k}.Checked := by decide", "",
        ])
        summary.append({"label": k, "cycle_front": cycle_front,
                        "opposite_front": front, "opposite_extras": extra,
                        "cycle_phases": len(c["cycle"]),
                        "transient_steps": len(transient),
                        "minimum_initial_coordinate": min(lower),
                        "minimum_reflection_margin": min(reflected)})
    lines.extend([
        "def catalogue : List CertifiedGeometry := [",
        ",\n".join(f"  ⟨row{k}, geometry{k}, row{k}_checked, geometry{k}_checked⟩"
                   for k in range(40, 76)), "]", "",
        "theorem labels_complete : catalogue.map (fun r => r.row.label) =",
        "    (List.range 36).map (fun i => i + 40) := by decide", "",
        "end Heraclitus.OutgoingData",
    ])
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text, rows = render()
    if args.write:
        TARGET.write_text(text)
    elif not TARGET.exists() or TARGET.read_text() != text:
        raise SystemExit("OutgoingData.lean differs from the current certificate extraction")
    print(json.dumps({"status": "binding matches", "rows": len(rows),
                      "phases": sum(r["cycle_phases"] for r in rows),
                      "transient_steps": sum(r["transient_steps"] for r in rows)}, indent=2))


if __name__ == "__main__":
    main()
