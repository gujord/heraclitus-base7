"""Bind return entrances to the already proved outgoing words.

The exporter is untrusted and imports no mathematical producer or checker.
Finite geometric and anchor-occupancy propositions are proved in Lean.
"""

import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "certificates/signed-machine.json"
TARGET = REPO / "formal/Heraclitus/ReturnBridgeData.lean"


def render(source=SOURCE):
    raw = source.read_bytes()
    data = json.loads(raw)
    rows = data["transitions"]
    if data["base"] != 7 or [r["k"] for r in rows] != list(range(40, 76)):
        raise ValueError("Expected base seven and labels 40..75")
    lines = ["import Heraclitus.ReturnBridge", "import Heraclitus.OutgoingWordData", "",
             "set_option autoImplicit false", "set_option maxRecDepth 100000", "",
             "/-! Generated by research/return_bridge/export_data.py.",
             "Source SHA-256: " + hashlib.sha256(raw).hexdigest(), "-/", "",
             "namespace Heraclitus.ReturnBridgeData", "",
             "open ReturnBridge OutgoingWord OutgoingWordData OutgoingData",
             "open FirstCrossingData SignedBoundaryData", ""]
    summary = []
    for row in rows:
        k = row["k"]
        anchor = row["first_exit"]["entry"]
        atom = f"({anchor})" if anchor < 0 else str(anchor)
        used = str(row["anchor_used"]).lower()
        lines += [f"def outgoing{k} : CertifiedRow :=",
                  f"  ⟨row{k}, geometry{k}, cycle{k}, row{k}_checked, geometry{k}_checked,",
                  f"    cycle{k}_checked, row{k}_inner, OutgoingWordData.entrance{k}_checked⟩", "",
                  f"def entry{k} : EntranceData outgoing{k} := ⟨{atom}, {used}⟩",
                  f"theorem entry{k}_checked : entry{k}.Checked := by decide", "",
                  f"def entrance{k} : CertifiedEntrance := ⟨outgoing{k}, entry{k}, entry{k}_checked⟩", ""]
        old = row["inner"]["sides"][str(-row["first_exit"]["sign"])]
        summary.append({"label": k, "anchor": anchor, "anchor_used": row["anchor_used"],
                        "old_front": old[0], "old_extras": old[1],
                        "recorded_outer_front": row["first_exit"]["front"]})
    lines += ["def catalogue : List CertifiedEntrance := [",
              ",\n".join(f"  entrance{k}" for k in range(40, 76)), "]", "",
              "theorem labels_complete : catalogue.map (fun e => e.outgoing.row.label) =",
              "    (List.range 36).map (fun i => i+40) := by decide", "",
              "theorem unused_anchor_labels :",
              "    (catalogue.filter (fun e => !e.data.anchorUsed)).map",
              "      (fun e => e.outgoing.row.label) = [43] := by decide", "",
              "end Heraclitus.ReturnBridgeData"]
    return "\n".join(lines) + "\n", summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--source", type=Path, default=SOURCE)
    args = parser.parse_args()
    content, rows = render(args.source)
    if args.write:
        if args.source.resolve() != SOURCE.resolve():
            raise SystemExit("Alternate sources can be checked but cannot replace committed data")
        TARGET.write_text(content)
    elif not TARGET.exists() or TARGET.read_text() != content:
        raise SystemExit("Return entrance source binding mismatch")
    print(json.dumps({"status": "binding matches", "rows": len(rows),
                      "used_anchors": sum(r["anchor_used"] for r in rows),
                      "unused_labels": [r["label"] for r in rows if not r["anchor_used"]]}, indent=2))


if __name__ == "__main__":
    main()
